#!/usr/bin/env python3
"""Generates ksp/src/Proto.cs from fabric/.../link/Proto.java so the two can never drift apart.
Usage: python3 tools/gen_proto_cs.py [--check]"""
import re, sys, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
src = (root / "fabric/src/main/java/dev/kerbalcraft/link/Proto.java").read_text(encoding="utf-8")
out = ["// <auto-generated> by tools/gen_proto_cs.py from Proto.java. Do not edit by hand.",
       "namespace KerbalCraft", "{", "\tpublic static class Proto", "\t{"]
def split_top(s):
    parts, depth, cur = [], 0, ""
    for ch in s:
        if ch == "(": depth += 1
        if ch == ")": depth -= 1
        if ch == "," and depth == 0: parts.append(cur); cur = ""
        else: cur += ch
    parts.append(cur); return parts
for line in src.splitlines():
    t = line.strip()
    m = re.match(r"public static final (int|long|double) (.*);\s*(//.*)?$", t)
    if m:
        typ = m.group(1)
        for d in split_top(m.group(2)):
            name, expr = [x.strip() for x in d.split("=", 1)]
            expr = re.sub(r"\(long\)\s*", "(long)", expr)
            out.append(f"\t\tpublic const {typ} {name} = {expr};")
        continue
    if t.startswith("//"):
        out.append("\t\t" + t)
out += ['\t\tpublic const string MAPPING_NAME = "Local\\\\KerbalCraft_v1";', "\t}", "}", ""]
text = "\n".join(out)
target = root / "ksp/src/Proto.cs"
if "--check" in sys.argv:
    ok = target.exists() and target.read_text(encoding="utf-8") == text
    print("Proto.cs is in sync with Proto.java" if ok else "Proto.cs is OUT OF SYNC; run tools/gen_proto_cs.py")
    sys.exit(0 if ok else 1)
target.write_text(text, encoding="utf-8"); print("wrote", target)
